def _score_to_probability(score, max_score=20):
    """Map a raw score to a 0–95% probability using a logistic-like curve."""
    normalized = min(1.0, score / max_score)
    # Logistic transform
    prob = 1 / (1 + math.exp(-8 * (normalized - 0.5)))
    return max(2, min(95, round(prob * 100, 1)))


def _modifiable_factors(factors):
    """Filter factors that are modifiable."""
    modifiable_keywords = [
        "adherence", "activity", "exercise", "smoking", "alcohol", "support", "diet"
    ]
    return [f for f in factors if any(kw in f.lower() for kw in modifiable_keywords)]


def _treatment_improvements(ctx):
    improvements = []
    if ctx["adherence_score"] < 80:
        improvements.append("Improve medication adherence (use pill organizers, reminders)")
    if ctx["exercise"] == "low":
        improvements.append("Increase physical activity — even 30 min/day of walking is beneficial")
    if ctx["smoking"]:
        improvements.append("Smoking cessation — single most impactful lifestyle change")
    if ctx["alcohol"]:
        improvements.append("Reduce alcohol consumption")
    if ctx["social_support"] != "high":
        improvements.append("Strengthen social support network (family, community groups)")
    return improvements


def _stratify_risk(readmission, mortality, emergency):
    scores = [readmission["probability"], mortality["probability"], emergency["probability"]]
    avg = sum(scores) / len(scores)
    overall = "CRITICAL" if avg >= 65 else "HIGH" if avg >= 45 else "MODERATE" if avg >= 25 else "LOW"

    return {
        "overall":          overall,
        "averageRisk":      round(avg, 1),
        "riskComponents": {
            "readmission":  readmission["level"],
            "mortality":    mortality["level"],
            "emergency":    emergency["level"],
        },
        "priorityAction": (
            "⚠️ Immediate medical review recommended" if overall == "CRITICAL"
            else "Schedule urgent specialist appointment" if overall == "HIGH"
            else "Schedule routine follow-up within 1–3 months" if overall == "MODERATE"
            else "Continue current management with regular monitoring"
        ),
    }


def _generate_insights(ctx, readmission, mortality, emergency):
    insights = []

    if readmission["probability"] > 50:
        insights.append({
            "type":    "warning",
            "title":   "High Readmission Risk",
            "message": "Consider enhanced discharge planning and follow-up scheduling.",
            "action":  "Schedule follow-up within 7 days of any hospital discharge",
        })

    if ctx["adherence_score"] < 70:
        insights.append({
            "type":    "action",
            "title":   "Low Medication Adherence",
            "message": f"Adherence score: {ctx['adherence_score']}%. Poor adherence increases all risk categories.",
            "action":  "Consider pill organizers, phone reminders, or pharmacist counseling",
        })

    if ctx["social_support"] == "low":
        insights.append({
            "type":    "info",
            "title":   "Limited Social Support",
            "message": "Patients with stronger social networks have significantly better outcomes.",
            "action":  "Connect with community health workers or support groups",
        })

    if ctx["smoking"]:
        insights.append({
            "type":    "action",
            "title":   "Smoking Cessation",
            "message": "Smoking is a major independent risk factor. Cessation within 1 year reduces cardiovascular risk by up to 50%.",
            "action":  "Enroll in a smoking cessation program — ask your doctor about Nicotine Replacement Therapy (NRT)",
        })

    if emergency["probability"] > 50:
        insights.append({
            "type":    "warning",
            "title":   "Elevated ER Risk",
            "message": f"{emergency['probability']}% likelihood of ER visit within 90 days.",
            "action":  "Establish clear care plan and emergency action plan with your physician",
        })

    if not insights:
        insights.append({
            "type":    "success",
            "title":   "Manageable Risk Profile",
            "message": "Your current risk profile is manageable with continued adherence to your treatment plan.",
            "action":  "Continue regular monitoring and maintain healthy lifestyle habits",
        })

    return insights


def _generate_trend_data(ctx):
    """Generate simulated trend data for visualization (12 months)."""
    adherence = ctx["adherence_score"]
    base      = 100 - adherence
    trend     = []

    for month in range(1, 13):
        # Controlled improvement or worsening trend
        delta = -0.5 if adherence >= 75 else 0.8
        val   = max(5, min(95, base + delta * month + (month % 3) * 0.5))
        trend.append({
            "month":     month,
            "label":     f"Month {month}",
            "riskScore": round(val, 1),
        })

    return {
        "riskTrend":  trend,
        "baseline":   base,
        "projection": "Improving" if adherence >= 75 else "Worsening without intervention",
    }
