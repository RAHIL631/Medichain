# ai/cdss/predictive_analytics.py
# Predictive Analytics Module — Phase 11
# Predicts clinical outcomes using rule-based scoring and ML heuristics.
#
# Models:
#   1. Disease Progression (trend analysis)
#   2. Readmission Risk (30-day)
#   3. Mortality Risk (severity scoring)
#   4. Emergency Prediction (90-day ER likelihood)
#   5. Treatment Success Prediction
#   6. Length of Stay Prediction
#
# Endpoint: POST /cdss/predictive-analytics

from flask import Blueprint, request, jsonify
import logging
import math
from datetime import datetime, timedelta

logger = logging.getLogger("cdss.predictive_analytics")

predictive_bp = Blueprint("predictive_analytics", __name__)


# ─────────────────────────────────────────────────────────────────────────────
# MAIN ROUTE
# ─────────────────────────────────────────────────────────────────────────────

@predictive_bp.route("/cdss/predictive-analytics", methods=["POST"])
def predictive_analytics():
    """
    Comprehensive Predictive Analytics Report.

    Request body:
    {
      "age": 65,
      "gender": "M",
      "conditions": ["heart_disease", "diabetes", "hypertension"],
      "medications": ["metformin", "lisinopril", "atorvastatin"],
      "vitals": { "systolic_bp": 150, "bmi": 29, "cholesterol": 220 },
      "labs": { "hba1c": 7.8, "creatinine": 1.4, "egfr": 55 },
      "recentHospitalizations": 1,
      "adherenceScore": 75,
      "smokingStatus": true,
      "alcoholUse": false,
      "exerciseFrequency": "low",
      "socialSupport": "moderate",
      "recentRecords": []
    }
    """
    try:
        data = request.get_json(silent=True) or {}
        logger.info(f"Predictive analytics request for age={data.get('age')}")

        age            = int(data.get("age", 45))
        gender         = str(data.get("gender", "M")).upper()
        conditions     = [str(c).lower() for c in data.get("conditions", [])]
        medications    = [str(m).lower() for m in data.get("medications", [])]
        vitals         = data.get("vitals", {})
        labs           = data.get("labs", {})
        recent_hosp    = int(data.get("recentHospitalizations", 0))
        adherence_score = int(data.get("adherenceScore", 80))
        smoking        = bool(data.get("smokingStatus", False))
        alcohol        = bool(data.get("alcoholUse", False))
        exercise       = str(data.get("exerciseFrequency", "moderate")).lower()
        social_support = str(data.get("socialSupport", "moderate")).lower()
        recent_records = data.get("recentRecords", [])

        ctx = dict(
            age=age, gender=gender, conditions=conditions, medications=medications,
            vitals=vitals, labs=labs, recent_hosp=recent_hosp,
            adherence_score=adherence_score, smoking=smoking, alcohol=alcohol,
            exercise=exercise, social_support=social_support,
        )

        # ── Run all prediction models ──────────────────────────────────────
        readmission  = _predict_readmission(ctx)
        mortality    = _predict_mortality(ctx)
        emergency    = _predict_emergency(ctx)
        treatment    = _predict_treatment_success(ctx)
        los          = _predict_length_of_stay(ctx)
        progression  = _predict_disease_progression(ctx)

        report = {
            "timestamp":      datetime.utcnow().isoformat() + "Z",
            "predictions": {
                "readmission30Day":   readmission,
                "mortalityRisk":      mortality,
                "emergencyRisk90Day": emergency,
                "treatmentSuccess":   treatment,
                "expectedLOS":        los,
                "diseaseProgression": progression,
            },
            "riskStratification":  _stratify_risk(readmission, mortality, emergency),
            "actionableInsights":  _generate_insights(ctx, readmission, mortality, emergency),
            "trendData":           _generate_trend_data(ctx),
            "disclaimer": (
                "Predictive analytics are generated by an AI system using rule-based "
                "and statistical models. Results are probabilistic estimates for clinical "
                "decision support only — NOT definitive diagnoses or prognoses. "
                "All clinical decisions must be made by qualified medical professionals."
            ),
        }

        logger.info(f"Predictive analytics completed — readmission: {readmission['probability']}%")
        return jsonify(report), 200

    except Exception as e:
        logger.error(f"Predictive analytics error: {e}")
        return jsonify({"error": "Predictive analytics error", "details": str(e)}), 500


